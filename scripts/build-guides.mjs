// Homepage "See an example for:" chips, from TRADE_PAGES. Only trades whose
// /for/ page exists, at most HOMEPAGE_TRADE_CHIPS; a "More trades" link is
// added only if a /for/ index page exists. Written between the
// <!-- trade-chips:start --> / <!-- trade-chips:end --> markers in
// public/index.html.
export function renderTradeChips(trades = TRADE_PAGES, { root = ROOT, max = HOMEPAGE_TRADE_CHIPS } = {}) {
  const live = trades.filter(t => existsSync(join(root, "public", "for", `${t.slug}.html`)));
  const shown = live.slice(0, max);
  const more = (live.length > max || existsSync(join(root, "public", "for", "index.html")))
    ? `\n      <li><a class="trade-chip trade-chip--more" href="/for/">More trades →</a></li>`
    : "";
  return `<nav class="trade-chips" aria-label="See an example for your trade">
    <p class="trade-chips__label">See an example for:</p>
    <ul class="trade-chips__list">
${shown.map(t => `      <li><a class="trade-chip" href="/for/${escAttr(t.slug)}" data-cta="trade_chip">${escText(t.label)}</a></li>`).join("\n")}${more}
    </ul>
  </nav>`;
}

export const TRADE_CHIPS_START = "<!-- trade-chips:start (generated by scripts/build-guides.mjs from data/guides.mjs TRADE_PAGES) -->";
export const TRADE_CHIPS_END = "<!-- trade-chips:end -->";

export function injectTradeChips(html, chips) {
  const i = html.indexOf(TRADE_CHIPS_START);
  const j = html.indexOf(TRADE_CHIPS_END);
  if (i === -1 || j === -1 || j < i) throw new Error("trade-chips markers missing in public/index.html");
  return html.slice(0, i + TRADE_CHIPS_START.length) + "\n  " + chips + "\n  " + html.slice(j);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const g of GUIDES) {
    const out = join(ROOT, "public", "for", `${g.slug}.html`);
    writeFileSync(out, renderGuide(g));
    console.log("wrote", out.replace(ROOT + "/", ""));
  }
  const home = join(ROOT, "public", "index.html");
  writeFileSync(home, injectTradeChips(readFileSync(home, "utf8"), renderTradeChips()));
  console.log("wrote trade chips into public/index.html");
}
