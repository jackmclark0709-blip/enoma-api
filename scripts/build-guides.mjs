// Renders every guide in data/guides.mjs to public/for/<slug>.html.
// Run: node scripts/build-guides.mjs
// The output is committed (the site is static), so re-run after editing a guide.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { GUIDES, CTA_LABEL, CTA_PROOF } from "../data/guides.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://enoma.io";

// Existing /for/ pages worth cross-linking from every guide.
const EVERGREEN_LINKS = [
  ["/for/website-for-plumbing-business", "Websites for plumbers"],
  ["/for/website-for-landscaping-business", "Websites for landscapers"],
  ["/for/website-for-hvac-business", "Websites for HVAC"],
  ["/for/website-for-electrician", "Websites for electricians"],
  ["/for/website-for-cleaning-business", "Websites for cleaners"],
  ["/for/website-builder-for-contractors", "Websites for contractors"],
  ["/for/how-to-get-more-plumbing-calls", "How to get more plumbing calls"],
  ["/for/how-to-get-more-lawn-care-customers", "How to get more lawn care customers"],
  ["/for/facebook-vs-website-local-business", "Facebook page vs. website"],
];

const GUIDE_LINK_TEXT = {
  "why-isnt-my-business-showing-up-on-google": "Not showing up on Google?",
  "angi-alternatives-for-contractors": "Angi alternatives",
  "how-to-get-snow-removal-customers": "Getting snow removal customers",
  "how-to-get-more-google-reviews-for-contractors": "Getting more Google reviews",
  "how-to-get-more-cleaning-clients": "Getting more cleaning clients",
  "how-to-get-more-hvac-customers": "Getting more HVAC customers",
  "enoma-vs-angi-thumbtack-yelp": "Enoma vs Angi, Thumbtack and Yelp",
  "do-i-need-a-website-if-i-have-a-google-business-profile": "Website vs. Google Business Profile",
  "thumbtack-vs-angi-for-contractors": "Thumbtack vs Angi",
  "are-yelp-ads-worth-it-for-contractors": "Are Yelp ads worth it?",
};

const escAttr = s => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const escText = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/'/g, "&#x27;").replace(/"/g, "&quot;");
const jsonLd = obj => `<script type="application/ld+json">${JSON.stringify(obj).replace(/</g, "\\u003c")}</script>`;
const stripTags = s => s.replace(/<br\s*\/?>/g, " ").replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();

export function renderGuide(g) {
  const url = `${SITE}/for/${g.slug}`;
  const headline = stripTags(g.h1);
  const dateLabel = new Date(g.published + "T12:00:00Z").toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric", timeZone: "UTC" });

  const faqSchema = {
    "@context": "https://schema.org", "@type": "FAQPage",
    mainEntity: g.faqs.map(f => ({ "@type": "Question", name: f.q, acceptedAnswer: { "@type": "Answer", text: f.a } })),
  };
  const articleSchema = {
    "@context": "https://schema.org", "@type": "Article",
    headline, description: g.description, url, mainEntityOfPage: url,
    image: `${SITE}/assets/og/enoma-default-v2.png`,
    datePublished: g.published, dateModified: g.updated || g.published,
    author: { "@type": "Organization", name: "Enoma", url: SITE },
    publisher: { "@type": "Organization", name: "Enoma", url: SITE, logo: { "@type": "ImageObject", url: `${SITE}/assets/logos/enoma-color-name.png` } },
  };
  const breadcrumbSchema = {
    "@context": "https://schema.org", "@type": "BreadcrumbList",
    itemListElement: [
      { "@type": "ListItem", position: 1, name: "Enoma", item: SITE },
      { "@type": "ListItem", position: 2, name: headline, item: url },
    ],
  };

  const related = [
    ...GUIDES.filter(o => o.slug !== g.slug).map(o => [`/for/${o.slug}`, GUIDE_LINK_TEXT[o.slug] || stripTags(o.h1)]),
    ...EVERGREEN_LINKS,
  ];

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <!-- Generated by scripts/build-guides.mjs from data/guides.mjs. Edit there, not here. -->
  <title>${escText(g.title)}</title>
  <meta name="description" content="${escAttr(g.description)}" />
  <meta name="robots" content="index, follow, max-image-preview:large" />
  <link rel="canonical" href="${url}" />
  <meta property="og:type" content="article" />
  <meta property="og:site_name" content="Enoma" />
  <meta property="og:title" content="${escAttr(g.title)}" />
  <meta property="og:description" content="${escAttr(g.description)}" />
  <meta property="og:image" content="${SITE}/assets/og/enoma-default-v2.png" />
  <meta property="og:url" content="${url}" />
  <meta property="article:published_time" content="${g.published}" />
  <meta name="twitter:card" content="summary_large_image" />
  <link rel="stylesheet" href="/styles/enoma.css" />
  <link rel="stylesheet" href="/styles/guide.css" />
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link href="https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,400;9..144,500;9..144,600;9..144,700;9..144,800&family=Instrument+Sans:wght@400;500;600;700&family=IBM+Plex+Mono:wght@400;500&display=swap" rel="stylesheet" />
  <link rel="icon" href="/favicon.ico" sizes="any" />
  <script async src="https://www.googletagmanager.com/gtag/js?id=G-S8XTG72Y2Y"></script>
  <script src="/scripts/clarity.js" defer></script>
  <script>window.dataLayer=window.dataLayer||[];function gtag(){dataLayer.push(arguments);}gtag('js',new Date());gtag('config','G-S8XTG72Y2Y',{content_group:'guide'});</script>
  ${jsonLd(faqSchema)}
  ${jsonLd(articleSchema)}
  ${jsonLd(breadcrumbSchema)}
</head>
<body data-page="${g.slug}">
<script src="/scripts/ref-capture.js"></script>
<script src="/scripts/funnel-track.js"></script>
<script type="module" src="/partials/nav.js"></script>

<section class="lp-hero">
  <div class="lp-hero__inner">
    <p class="lp-hero__eyebrow">${g.eyebrow}</p>
    <h1 class="lp-hero__h1">${g.h1}</h1>
    <p class="lp-hero__sub">${g.heroSub}</p>
    <div class="lp-hero__actions">
      <a href="/get-your-website" class="btn-primary" data-cta="hero">${CTA_LABEL}</a>
      <a href="/case-studies/conways-landscaping" class="btn-secondary" data-cta="hero-proof">See the Conway's results</a>
    </div>
    <p class="lp-hero__proof">${CTA_PROOF}</p>
  </div>
</section>

<section class="lp-proof" aria-label="Results from a real Enoma page">
  <div class="lp-proof__inner">
    <div class="lp-stat"><p class="lp-stat__n">36</p><p class="lp-stat__l">taps to call or email from Conway's Landscaping's Enoma page</p></div>
    <div class="lp-stat"><p class="lp-stat__n">6</p><p class="lp-stat__l">quote requests sent straight to the owner through the page's form</p></div>
    <div class="lp-stat"><p class="lp-stat__n">$0</p><p class="lp-stat__l">spent on ads. The page gets found in Google search on its own</p></div>
  </div>
  <p class="lp-proof__note">One real page for a small lawn care company in Agawam, MA. <a href="/case-studies/conways-landscaping">Read how it works →</a></p>
</section>

<article class="lp-article">
  <div class="lp-article__inner">
    <p class="lp-updated">By the Enoma team &nbsp;·&nbsp; Updated <time datetime="${g.updated || g.published}">${dateLabel}</time></p>
${g.article.trim()}
  </div>
</article>

<section class="lp-faq">
  <div class="lp-faq__inner">
    <p class="lp-faq__label">Common questions</p>
    <h2 class="lp-faq__h2">${headline}: common questions</h2>
    <div class="lp-faq__list">
${g.faqs.map(f => `      <div class="lp-faq__item">
        <h3 class="lp-faq__q">${escText(f.q)}</h3>
        <p class="lp-faq__a">${escText(f.a)}</p>
      </div>`).join("\n")}
    </div>
  </div>
</section>

<section class="lp-cta">
  <div class="lp-cta__inner">
    <h2 class="lp-cta__h2">${g.ctaH2}</h2>
    <p class="lp-cta__sub">${g.ctaSub}</p>
    <div class="lp-cta__actions">
      <a href="/get-your-website" class="btn-primary" data-cta="final">${CTA_LABEL}</a>
      <a href="/examples" class="btn-secondary" data-cta="final-examples">See live examples</a>
    </div>
    <p class="lp-cta__proof">${CTA_PROOF}</p>
  </div>
</section>

<nav class="lp-related" aria-label="More for local service businesses">
  <div class="lp-related__inner">
    <h2 class="lp-related__h2">More for local service businesses</h2>
    <div class="lp-related__grid">
${related.map(([href, text]) => `      <a href="${href}">${text}</a>`).join("\n")}
    </div>
  </div>
</nav>

<div id="footer"></div>
<script>fetch('/partials/footer.html').then(r=>r.text()).then(html=>{document.getElementById('footer').innerHTML=html});</script>
<script src="/scripts/global-cta.js" defer></script>
<script src="/scripts/cta-track.js" defer></script>
</body>
</html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const g of GUIDES) {
    const out = join(ROOT, "public", "for", `${g.slug}.html`);
    writeFileSync(out, renderGuide(g));
    console.log("wrote", out.replace(ROOT + "/", ""));
  }
}
