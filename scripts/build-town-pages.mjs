// Builds the "website for <trade> in <town>" landing pages from
// data/town-pages.json into public/for/, plus the slug list the sitemap reads.
// Run: node scripts/build-town-pages.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { renderTownPage, pageSlug } from "../api/_lib/town-pages.js";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(fs.readFileSync(path.join(root, "data/town-pages.json"), "utf8"));
const outDir = path.join(root, "public/for");

// Retired pairs (Oct 2026: town pages without a local client were folded into
// the national trade pages and 301'd in vercel.json) are kept in the data for
// reference but not built, listed in the sitemap, or linked as siblings.
const live = data.pairs.filter(p => !p.retired);
const slugs = [];
for (const p of live) {
  const slug = pageSlug(p);
  fs.writeFileSync(path.join(outDir, `${slug}.html`), renderTownPage(p, { ...data, pairs: live }));
  slugs.push(slug);
}

fs.writeFileSync(path.join(root, "api/_lib/town-pages-slugs.js"),
  `// Generated by scripts/build-town-pages.mjs from data/town-pages.json. Do not edit by hand.\n` +
  `export const TOWN_PAGE_SLUGS = ${JSON.stringify(slugs, null, 2)};\n`);

console.log(`Built ${slugs.length} town pages.`);
