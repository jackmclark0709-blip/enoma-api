// Writes api/_lib/stock-library-data.js from scripts/stock-manifest.txt,
// minus the ids in scripts/stock-rejected.txt (hand review of the copies).
// Usage: node scripts/build-stock-library-data.mjs
import fs from "node:fs";
const lines = fs.readFileSync(new URL("./stock-manifest.txt", import.meta.url), "utf8").split("\n").map(l => l.trim()).filter(Boolean);
const rejectedPath = new URL("./stock-rejected.txt", import.meta.url);
const rejected = new Set(fs.existsSync(rejectedPath) ? fs.readFileSync(rejectedPath, "utf8").split(/\s+/).filter(Boolean) : []);
const rows = lines.map(l => l.split(/\s+/)).map(([persona, tag, , id]) => ({ id, persona, tag })).filter(r => r.id && !rejected.has(r.id));
const out = `// Generated by scripts/build-stock-library-data.mjs. Don't edit by hand.
// Every id has public/stock/<id>-800.webp and <id>-1600.webp.
export const STOCK_LIBRARY = Object.freeze(${JSON.stringify(rows, null, 0).replace(/},{/g, "},\n  {").replace(/^\[/, "[\n  ").replace(/\]$/, ",\n]")});
`;
fs.writeFileSync(new URL("../api/_lib/stock-library-data.js", import.meta.url), out);
console.log(`${rows.length} photos (${rejected.size} rejected)`);
